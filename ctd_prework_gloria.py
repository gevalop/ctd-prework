#Daily job search progress program
#It asks for today's date, a job title, and if resume was emailed.
#It also has a number count of applications for the day.

date = input("Enter today's date: ")
job = input(' Enter job title: ')
emailed_resume = input(' Did you email your resume "yes" or "no": ')

if emailed_resume.strip().lower() == 'yes':
    print("Congratulations! On", date, "you applied to " + job + ".")
    applications = 1
else:
    print("Reminder, email your resume.")
    applications = 0

#Number of applied jobs today.

print("Number of job applications today:", applications)




